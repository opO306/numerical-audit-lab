"""ONE-TIME generator for the Gate 0 benchmark 3 fixture. Never re-run to replace it.

Follows Algorithm 6.1 GenDot(n, c) of Ogita, Rump, Oishi, "Accurate Sum and Dot
Product", SIAM J. Sci. Comput. 26(6):1955-1988, 2005, as reconstructed from
memory by the implementer (the paper text was not reachable from the build
environment). The line-by-line reading used is in docs/BENCHMARK3_SELECTION.md
so the designer can diff it against the paper.

The benchmark does not depend on this reconstruction being faithful: the
vectors are frozen, and the Lab computes their exact dot product itself. What
depends on it is only the label "generated by GenDot".

Randomness lives here and only here: Python's Mersenne Twister with a seed
fixed before the first run. The fixture, not this script, is the benchmark.

    python -m benchmarks.gate0.gendot_generate      (refuses if the fixture exists)
"""
from __future__ import annotations

import hashlib
import json
import math
import platform
import random
import sys
from fractions import Fraction
from pathlib import Path

N, COND, SEED = 50, 10 ** 25, 20261001
FIXTURE = Path(__file__).parent / "fixtures" / "gendot_n50_c1e25_v1.json"


def mround(v: float) -> int:
    """MATLAB round for v >= 0: half away from zero."""
    assert v >= 0
    return math.floor(v + 0.5)


def dot_rounded(xs, ys) -> float:
    """Dot_: the exact dot product rounded to nearest binary64 (Fraction -> float is correctly rounded)."""
    return float(sum((Fraction(a) * Fraction(b) for a, b in zip(xs, ys)), Fraction(0)))


def gendot(n: int, c: int, rng: random.Random):
    n2 = mround(n / 2)
    b = math.log2(c)
    x, y = [0.0] * n, [0.0] * n
    e = [mround(rng.random() * b / 2) for _ in range(n2)]
    e[0] = mround(b / 2) + 1
    e[-1] = 0
    for i in range(n2):
        x[i] = (2 * rng.random() - 1) * 2.0 ** e[i]
    for i in range(n2):
        y[i] = (2 * rng.random() - 1) * 2.0 ** e[i]
    m = n - n2
    lin = [b / 2 + (0 - b / 2) * k / (m - 1) for k in range(m)]       # linspace(b/2, 0, n - n2)
    e2 = [mround(v) for v in lin]
    for i in range(n2, n):
        x[i] = (2 * rng.random() - 1) * 2.0 ** e2[i - n2]
        y[i] = ((2 * rng.random() - 1) * 2.0 ** e2[i - n2] - dot_rounded(x[:i], y[:i])) / x[i]
    keys = [rng.random() for _ in range(n)]                          # [~, ii] = sort(rand(n, 1))
    ii = sorted(range(n), key=lambda k: keys[k])
    x, y = [x[k] for k in ii], [y[k] for k in ii]
    d = dot_rounded(x, y)
    num = 2 * sum((abs(Fraction(a) * Fraction(b)) for a, b in zip(x, y)), Fraction(0))
    C = num / abs(Fraction(d)) if d != 0 else None
    return x, y, d, C


def main() -> int:
    if FIXTURE.exists():
        print(f"refusing: {FIXTURE} exists and is frozen")
        return 1
    x, y, d, C = gendot(N, COND, random.Random(SEED))
    bits = lambda v: f"{int.from_bytes(__import__('struct').pack('>d', v), 'big'):016x}"   # noqa: E731
    fixture = {
        "name": "gendot_n50_c1e25_v1",
        "algorithm": "GenDot (Ogita, Rump, Oishi 2005, Algorithm 6.1), implementer's reconstruction; see docs/BENCHMARK3_SELECTION.md",
        "parameters": {"n": N, "c": "1e25", "seed": SEED, "prng": "Python random.Random (MT19937)"},
        "generator_sha256_lf": hashlib.sha256(Path(__file__).read_bytes().replace(b"\r\n", b"\n")).hexdigest(),
        "generated_with": {"python": platform.python_version(), "system": platform.system()},
        "x_bits": [bits(v) for v in x],
        "y_bits": [bits(v) for v in y],
        "x_hex": [v.hex() for v in x],
        "y_hex": [v.hex() for v in y],
        "generator_d_bits": bits(d),
        "generator_d_hex": d.hex(),
        "generator_condition_number": None if C is None else f"{float(C):.6e}",
    }
    FIXTURE.parent.mkdir(exist_ok=True)
    FIXTURE.write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(FIXTURE, hashlib.sha256(FIXTURE.read_bytes()).hexdigest(), fixture["generator_condition_number"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
